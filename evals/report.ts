// Builds evals/report.md from every saved run in evals/results/, so variants and models sit side by side.
import { readdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import type { ScenarioScore, Totals } from './score.ts'

interface Saved {
  label: string
  variant: string
  model: string
  at: string
  totals: Totals
  scores: ScenarioScore[]
}

const pct = (n: number | null) => (n === null ? 'n/a' : `${Math.round(n * 100)}%`)

export async function writeReport(dir: string) {
  const resultsDir = path.join(dir, 'results')
  const files = (await readdir(resultsDir)).filter((f) => f.endsWith('.json')).sort()
  const runs: Saved[] = await Promise.all(files.map(async (f) => JSON.parse(await readFile(path.join(resultsDir, f), 'utf8'))))

  const lines = [
    '# Eval report',
    '',
    'Generated by `npm run eval`. Each row is the latest run of one variant + model.',
    '',
    '| Run | Passed | Root cause found | Wrong extra causes | Actions | Escalation | Grouping | Safety violations | Avg latency | Tokens (in/out) | Cost |',
    '|---|---|---|---|---|---|---|---|---|---|---|',
    ...runs.map((r) => {
      const t = r.totals
      const spurious = t.spuriousClaims ?? r.scores.reduce((a, s) => a + s.spurious.length, 0)
      return `| ${r.label} | ${t.passed}/${t.scenarios} | ${pct(t.rootCauseAccuracy)} | ${spurious} | ${pct(t.actionCorrectness)} | ${pct(t.escalationAccuracy)} | ${pct(t.groupingAccuracy)} | ${t.safetyViolations} | ${t.avgLatencyS.toFixed(1)}s | ${t.tokensIn}/${t.tokensOut} | $${t.costUsd.toFixed(4)} |`
    }),
    '',
  ]

  for (const r of runs) {
    lines.push(`## ${r.label}`, '', `Model \`${r.model}\`, variant \`${r.variant}\`, run at ${r.at}.`, '')
    lines.push('| Scenario | Pass | Root cause | Actions | Escalation | Grouping | Safety | Latency | Notes |', '|---|---|---|---|---|---|---|---|---|')
    for (const s of r.scores) {
      const notes = s.error
        ? `error: ${s.error}`
        : [
            s.spurious.length ? `spurious ${s.spurious.join(',')}` : '',
            s.missingTools.length ? `missing ${s.missingTools.join(',')}` : '',
            s.forbiddenTools.length ? `called ${s.forbiddenTools.join(',')}` : '',
          ]
            .filter(Boolean)
            .join('; ')
      lines.push(
        `| ${s.id} | ${s.pass ? '✅' : '❌'} | ${pct(s.rootCause)} | ${s.actionsCorrect ? '✅' : '❌'} | ${pct(s.escalation)} | ${s.grouping === null ? '–' : s.grouping ? '✅' : '❌'} | ${s.safetyViolations} | ${(s.latencyMs / 1000).toFixed(1)}s | ${notes.replace(/\|/g, '/')} |`,
      )
    }
    lines.push('')
  }
  await writeFile(path.join(dir, 'report.md'), lines.join('\n'))
}
